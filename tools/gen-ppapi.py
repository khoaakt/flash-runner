#!/usr/bin/env python3
"""Generate the PPAPI bridge tables from the vendored Chromium headers.

Outputs
  web/ppapi-sigs.js                  signature table the JS Pepper host uses to decode guest calls
  guest/pepper-host/gen/stubs.S      one 3-instruction stub per PPB method: mov $id,%eax; int $0x82; ret
  guest/pepper-host/gen/tables.c     PPB_* interface tables (arrays of stub pointers) + name lookup

A PPB call needs no marshalling code in the guest: the stub traps with the method id in EAX while the
cdecl frame is still on the stack, and the host decodes the arguments from guest memory using the
signature table. Struct returns use the i386 hidden-pointer convention; double/float returns are
passed back in EDX:EAX / EAX and loaded onto the x87 stack by a flavoured stub.
"""
import json, os, sys, re
sys.path.insert(0, os.path.dirname(__file__))
import ppapi_parse

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')

ARG_CODES = {
    'struct PP_Var': 'V', 'PP_Var': 'V',
    'struct PP_CompletionCallback': 'C',
    'struct PP_ArrayOutput': 'A',
    'struct PP_Point': 'P', 'struct PP_FloatPoint': 'F', 'struct PP_TouchPoint': 'T',
    'double': 'd', 'PP_Time': 'd', 'PP_TimeTicks': 'd', 'PP_TimeDelta': 'd',
    'float': 'f', 'GLfloat': 'f', 'GLclampf': 'f',
    'int64_t': 'I', 'uint64_t': 'I', 'PP_TraceEventTime': 'I',
}
WORDS = {'i': 1, 'p': 1, 'f': 1, 'd': 2, 'I': 2, 'V': 4, 'C': 3, 'A': 2, 'P': 2, 'F': 2, 'T': 6}

def code_of(t):
    t = t.strip()
    if t in ARG_CODES:
        return ARG_CODES[t]
    if '*' in t or '[' in t or t == 'fnptr' or '&' in t:
        return 'p'
    return 'i'

# Methods implemented natively in the guest (they must block the calling guest thread while running tasks).
OVERRIDES = {
    ('PPB_MessageLoop;1.0', 'Run'): 'pepper_ml_run',
    ('PPB_Flash_MessageLoop;0.1', 'Run'): 'pepper_flash_ml_run',
}

def main():
    structs, by_string = ppapi_parse.interfaces()
    # interface strings we expose: every PPB_* string; PPP_* only recorded for offsets.
    ppb = {s: n for s, n in by_string.items() if s.startswith('PPB_')}
    ppp = {s: n for s, n in by_string.items() if s.startswith('PPP_')}
    methods = []   # global id -> method
    ifaces = {}
    for s in sorted(ppb):
        sn = ppb[s]
        base = len(methods)
        ms = []
        for m in structs[sn]['methods']:
            args = [code_of(t) for t, n in m['args']]
            rc = m['ret'].strip()
            rcode = 'v' if rc == 'void' else code_of(rc)
            entry = {'id': len(methods), 'iface': s, 'name': m['name'], 'a': ''.join(args), 'r': rcode,
                     'an': [n for t, n in m['args']]}
            methods.append(entry)
            ms.append(entry['id'])
        ifaces[s] = {'struct': sn, 'ids': ms}
    pppj = {s: {'struct': n, 'methods': [m['name'] for m in structs[n]['methods']]} for s, n in sorted(ppp.items())}

    with open(os.path.join(ROOT, 'web', 'ppapi-sigs.js'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('// GENERATED by tools/gen-ppapi.py from third_party/ppapi — do not edit.\n')
        f.write('// Arg/return codes: i=int32/enum/bool p=pointer f=float d=double(2w) I=int64(2w) V=PP_Var(4w)\n')
        f.write('//   C=PP_CompletionCallback(3w) A=PP_ArrayOutput(2w) P=PP_Point F=PP_FloatPoint T=PP_TouchPoint (by value).\n')
        f.write('// Return V/P/F/T use the i386 hidden struct pointer (first stack word); r=v is void.\n')
        f.write('export const METHODS = ' + json.dumps([{k: v for k, v in m.items() if k != 'an'} | {'an': m['an']} for m in methods], separators=(',', ':')) + ';\n')
        f.write('export const PPB = ' + json.dumps({s: v['ids'] for s, v in ifaces.items()}, separators=(',', ':')) + ';\n')
        f.write('export const PPP = ' + json.dumps(pppj, separators=(',', ':')) + ';\n')

    os.makedirs(os.path.join(ROOT, 'guest', 'pepper-host', 'gen'), exist_ok=True)
    with open(os.path.join(ROOT, 'guest', 'pepper-host', 'gen', 'stubs.S'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* GENERATED by tools/gen-ppapi.py */\n\t.text\n')
        for m in methods:
            f.write(f'\t.globl ppb_stub_{m["id"]}\n\t.type ppb_stub_{m["id"]},@function\nppb_stub_{m["id"]}:\n\tmovl ${m["id"]}, %eax\n\tint $0x82\n')
            if m['r'] == 'd':
                f.write('\tpushl %edx\n\tpushl %eax\n\tfldl (%esp)\n\taddl $8, %esp\n')
            elif m['r'] == 'f':
                f.write('\tpushl %eax\n\tflds (%esp)\n\taddl $4, %esp\n')
            # i386 SysV: a function returning a struct in memory pops the hidden pointer itself.
            f.write('\tret $4\n' if m['r'] in 'VPFT' else '\tret\n')
        f.write('\t.section .note.GNU-stack,"",@progbits\n')
    with open(os.path.join(ROOT, 'guest', 'pepper-host', 'gen', 'tables.c'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* GENERATED by tools/gen-ppapi.py */\n#include <string.h>\n#include "../ppb_table.h"\n')
        f.write('extern void ' + ', '.join(f'ppb_stub_{m["id"]}()' for m in methods) + ';\n')
        f.write('extern void ' + ', '.join(f'{v}()' for v in sorted(set(OVERRIDES.values()))) + ';\n')
        names = []
        for i, (s, v) in enumerate(sorted(ifaces.items())):
            tn = f'tbl_{i}'
            ents = []
            for j in v['ids']:
                ov = OVERRIDES.get((s, methods[j]['name']))
                ents.append(ov if ov else f'ppb_stub_{j}')
            f.write(f'static void *{tn}[] = {{ ' + ', '.join(ents) + ' };\n')
            names.append((s, tn, len(v['ids'])))
        f.write('const struct ppb_iface ppb_ifaces[] = {\n')
        for s, tn, n in names:
            f.write(f'  {{ "{s}", {tn}, {n} }},\n')
        f.write('  { 0, 0, 0 }\n};\n')
    print(f'{len(methods)} PPB methods in {len(ifaces)} interfaces; {len(pppj)} PPP interfaces')

if __name__ == '__main__':
    main()
