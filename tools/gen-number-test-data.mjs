// Regenerate crates/emu/src/lir/number_expr_data.rs from real NanoJIT captures.
//   node tools/gen-number-test-data.mjs spec.json
// spec.json: { "pool": [[address, bitsHex], ...], "mask": "2b1af660",
//              "sources": [ { "capture": "path/to/capture.json", "names": { "<capture index>": "rust_case_name" } } ] }
// Capture a fixture with:  node web/flash-smoke.mjs --plugin <plugin> --swf tests/swf/<fixture>.swf --seconds 10 \
//                            --nanojit-capture capture.json --capture-methods 64
// Bytes run from the method entry through the epilogue `ret`; absolute core/mask/pool addresses stay as captured
// (the tests relocate them). Every capture must report the same MethodFrame core address.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const spec = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const out = []; let core;
for (const { capture, names } of spec.sources) {
  const captures = JSON.parse(readFileSync(capture, 'utf8')).captures;
  for (const [index, name] of Object.entries(names)) {
    const c = captures[index], bytes = Buffer.from(c.nativePrefix);
    const end = bytes.indexOf(Buffer.from('8be55dc3', 'hex')) + 4;     // mov esp,ebp; pop ebp; ret
    if (end < 4) throw new Error(`${name}: no epilogue in the captured bytes`);
    out.push({ name, hex: bytes.subarray(0, end).toString('hex') });
    const k = new DataView(Uint8Array.from(c.records[8].bytes).buffer).getUint32(0, true);
    if (core === undefined) core = k; else if (core !== k) throw new Error('core address differs between captures');
  }
}
const pool = spec.pool.map(([address, bits]) => `(0x${address}, 0x${bits})`).join(', ');
let rs = `//! Real .363 NanoJIT native Number methods (offline data, generated by tools/gen-number-test-data.mjs).\n`
  + `//! Bytes run from the method entry through the epilogue \`ret\`; absolute core/mask/pool addresses are the original\n`
  + `//! capture values and are relocated by the tests.\n`
  + `pub(super) const CAPTURED_CORE: u32 = 0x${core.toString(16)};\npub(super) const CAPTURED_MASK: u32 = 0x${spec.mask};\n`
  + `/// Real constant-pool slots (address, double bits) the captured methods load from.\n`
  + `pub(super) const CAPTURED_POOL: [(u32, u64); ${spec.pool.length}] = [${pool}];\n`
  + `pub(super) const SHAPES: [(&str, &str); ${out.length}] = [\n`;
for (const o of out) rs += `    ("${o.name}", "${o.hex}"),\n`;
rs += '];\n';
writeFileSync(fileURLToPath(new URL('../crates/emu/src/lir/number_expr_data.rs', import.meta.url)), rs);
console.log(`${out.length} shapes, core ${core.toString(16)}`);
